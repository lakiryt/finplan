/** 相殺の考え方（両方向）。相殺が原則 */
export function OffsetInfo() {
  return (
    <>
      <p>条件に当たる記録をその側から除き、反対側からも同じ額だけ差し引きます。収支は変わらず、収入と支出の見え方だけが変わります。</p>
      <ul>
        <li>
          収入 → 支出: 割り勘の回収・返金・ポイントなど、支出の打ち消し。例: 4,000円を立て替えて1,500円を回収 → 外食は2,500円（除くだけだと4,000円のまま）
        </li>
        <li>
          支出 → 収入: 家賃など、生活費の範囲から外したいもの。例: 家賃を給与から差し引く → 支出は家賃以外の生活費、収入は家賃を払った後に使えるお金
        </li>
      </ul>
      <p className="muted">条件の画面で、反対側の差し引く先のカテゴリーを選ぶと相殺になります（選ばなければ除外）。</p>
    </>
  )
}

/** 除外の考え方。除外は、相手方が家計簿の外にある相殺 */
export function ExcludeInfo() {
  return (
    <>
      <p>
        積立や貯金の引き出しは、家計簿の外（証券口座など）を相手方にした相殺のようなものです。積立で出たお金と引き出しで戻ったお金は外で打ち消し合うので、両方を除きます。これだけを除いたものが、総務省の家計調査でいう「実収入」「実支出」です。
      </p>
      <p>例: 給与20万円と、貯金からの引き出し3万円があった月 → 引き出しを除くと収入は20万円です。</p>
      <p className="muted">
        外で打ち消し合わずに残る分（運用の損益など）は、収支に出てきません。臨時収入や家賃のような、本当に受け取った・使ったお金を除くと、収支が実際と違う数字になります（範囲から外したいなら相殺を使います）。
      </p>
      {SOURCES}
    </>
  )
}
